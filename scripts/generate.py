#!/usr/bin/env python3
"""Deterministic DTO/operation generation from pinned, vendored contracts. Python stdlib only.

`--vendor` copies the manifest modules from a webmania-openapi checkout (`--source`, Git revision
`--revision`, default HEAD) into contracts/. Generation refuses vendored modules whose contract_digest
(SHA-256 of the canonical JSON of the sorted "module path -> SHA-256" map) differs from the pin.
"""
from pathlib import Path
import json, re, hashlib, subprocess, sys
ROOT=Path(__file__).resolve().parents[1]
CONTRACT_DIGEST='371a499f74012bb6b41f23642869dee4954e8394dcba7642edc701aedb3dd59e'
def option(name,default):
 return sys.argv[sys.argv.index(name)+1] if name in sys.argv else default
SOURCE=Path(option('--source',str(ROOT.parent/'webmania-openapi')))
REVISION=option('--revision','HEAD')
def gitfile(p): return subprocess.check_output(['git','-C',str(SOURCE),'show',REVISION+':'+p])
def ident(s):
 s=re.sub(r'[^A-Za-z0-9_]','_',s)
 s=''.join(w[:1].upper()+w[1:] for w in s.split('_') if w)
 return ('N'+s if s[:1].isdigit() else s) or 'Value'
def q(s):return json.dumps(s,ensure_ascii=False)
manifest=json.loads(gitfile('contracts/manifest.json')) if '--vendor' in sys.argv else json.loads((ROOT/'contracts/manifest.json').read_text(encoding='utf-8'))
if '--vendor' in sys.argv:
 for p in manifest['contracts']:
  dst=ROOT/p;dst.parent.mkdir(parents=True,exist_ok=True);dst.write_bytes(gitfile(p))
 (ROOT/'contracts/manifest.json').write_bytes(gitfile('contracts/manifest.json'))
digest=hashlib.sha256(json.dumps(dict(sorted((p,hashlib.sha256((ROOT/p).read_bytes()).hexdigest()) for p in manifest['contracts'])),separators=(',',':'),ensure_ascii=False).encode('utf-8')).hexdigest()
if digest!=CONTRACT_DIGEST:raise SystemExit('Vendored contract_digest '+digest+' differs from the pinned '+CONTRACT_DIGEST)
models=['// <auto-generated />','#nullable enable','using System.Text.Json;','using System.Text.Json.Serialization;','namespace Webmania;']
methods=['// <auto-generated />','#nullable enable','namespace Webmania;','public sealed partial class WebmaniaClient {']
ops=[]; locks=[]; declarations={}; cache={}; module=''; doc=None; namespaceprefix=''; pointers={}
def typ(s,name,force=False):
 if not isinstance(s,dict):return 'JsonElement'
 if '$ref' in s:return typ(doc['components']['schemas'][s['$ref'].split('/')[-1]],namespaceprefix+ident(s['$ref'].split('/')[-1]),True)
 source=s
 if 'allOf' in s and not s.get('type') and not s.get('properties'):
  merged={}
  def merge(x):
   if '$ref' in x:merge(doc['components']['schemas'][x['$ref'].split('/')[-1]])
   merged.update(x.get('properties',{}))
   for b in x.get('allOf',[]):merge(b)
  merge(s)
  if merged:s=dict(s,type='object',properties=merged)
 t=s.get('type')
 if t is None and 'enum' in s:
  ts=[]
  for x in s['enum']:
   vt='null' if x is None else 'boolean' if isinstance(x,bool) else 'integer' if isinstance(x,int) else 'number' if isinstance(x,float) else 'string'
   if vt not in ts:ts.append(vt)
  s=dict(s,type=ts[0] if len(ts)==1 else ts);t=s['type']
 # Objects may have anyOf/allOf conditionals, but retain their complete declared properties.
 if t=='object' or 'properties' in s:
  if name in declarations:return name
  declarations[name]=True
  lines=[f'[SchemaSource({q(module)}, {q(pointers.get(id(source), "operation:"+name))}, {q(hashlib.sha256(json.dumps(s,sort_keys=True,ensure_ascii=False,separators=(",",":")).encode()).hexdigest())})]',f'public sealed class {name} : JsonModel {{']
  used={name.lower(),'extras'}
  for pn,ps in s.get('properties',{}).items():
   cn=ident(pn)
   if cn.lower() in used:cn+='Field'+hashlib.sha256(pn.encode()).hexdigest()[:6]
   used.add(cn.lower());pt=typ(ps,name+cn)
   lines += [f' [JsonPropertyName({q(pn)})]', ' [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]',f' public Optional<{pt}> {cn} {{ get; set; }}']
  lines+=['}'];models.extend(lines);return name
 if t=='array':return f'List<{typ(s.get("items",{}),name+"Item")}>'
 if 'anyOf' in s or 'oneOf' in s or isinstance(t,list):
  variants=s.get('anyOf',s.get('oneOf',[{'type':x} for x in t] if isinstance(t,list) else []))
  if name in declarations:return name
  declarations[name]=True
  vtypes=[]
  for i,x in enumerate(variants):
   vt=typ(x,name+'Variant'+str(i+1));
   if vt not in vtypes:vtypes.append(vt)
  lines=[f'[SchemaSource({q(module)}, {q(pointers.get(id(source), "operation:"+name))}, {q(hashlib.sha256(json.dumps(source,sort_keys=True,ensure_ascii=False,separators=(",",":")).encode()).hexdigest())})]', f'[JsonConverter(typeof(JsonUnionConverter<{name}>))]',f'public sealed class {name} : JsonUnion {{',f' public {name}(JsonElement value) : base(value) {{ }}']
  for i,vt in enumerate(vtypes):
   if vt=='JsonElement':continue
   lines += [f' public static {name} FromVariant{i+1}({vt} value) => new(WebmaniaJson.ToElement(value));',f' public {vt}? AsVariant{i+1}() => WebmaniaJson.FromElement<{vt}>(Value);']
  lines+=['}'];models.extend(lines);return name
 if t=='string':return 'string'
 if t=='boolean':return 'bool'
 if t in ('integer','number'):return 'JsonNumber'
 return 'JsonElement'
for path in manifest['contracts']:
 module=path;raw=(ROOT/path).read_bytes();doc=json.loads(raw);pointers={}
 def index(value,pointer):
  if isinstance(value,dict):
   pointers[id(value)]=pointer
   for k,v in value.items():index(v,pointer+'/'+k.replace('~','~0').replace('/','~1'))
  elif isinstance(value,list):
   for i,v in enumerate(value):index(v,pointer+'/'+str(i))
 index(doc,'#')
 namespaceprefix=ident(path.replace('contracts/','').replace('.openapi.json','').replace('/','_').replace('-','_'))
 locks.append({'path':path,'sha256':hashlib.sha256(raw).hexdigest()})
 for sn,ss in doc.get('components',{}).get('schemas',{}).items():typ(ss,namespaceprefix+ident(sn),True)
 for route,item in doc['paths'].items():
  for method,op in item.items():
   if not isinstance(op,dict) or 'operationId' not in op:continue
   oid=op['operationId'];name=ident(oid);pn=name+'Parameters';params=op.get('parameters',[])
   ps={'type':'object','properties':{p['name']:p['schema'] for p in params},'required':[p['name'] for p in params if p.get('required')], 'additionalProperties':False}
   body=next(iter(op.get('requestBody',{}).get('content',{}).values()),{}).get('schema')
   if body is not None:
    ps['properties']['body']=body
    if op['requestBody'].get('required'):ps['required'].append('body')
   pointers[id(ps)]='#/paths/'+route.replace('~','~0').replace('/','~1')+'/'+method
   typ(ps,pn)
   resp={k:v for k,v in op['responses'].items() if k.startswith('2')}
   jsonres=[v['content']['application/json']['schema'] for v in resp.values() if 'application/json' in v.get('content',{}) and 'schema' in v['content']['application/json']]
   binary=('files.openapi.json' in path or oid in ['fiscalDownloadReport','fiscalDownloadReportV2','monitorDownloadReport'])
   rt='FileResult' if binary else (typ(jsonres[0],name+'Result') if jsonres else 'JsonElement')
   ret='FileResult' if binary else f'ApiResponse<{rt}>'
   invoke='ExecuteFileAsync' if binary else f'ExecuteAsync<{rt}>'
   methods.append(f' public Task<{ret}> {name}Async({pn} parameters, CancellationToken cancellationToken = default) => {invoke}({q(oid)}, parameters, cancellationToken);')
   auth=('report-file' if oid in ('fiscalDownloadReport','fiscalDownloadReportV2') else 'api1-files' if path=='contracts/api1/files.openapi.json' else 'api2-files' if path=='contracts/api2/emitter-files.openapi.json' else 'reseller' if '/api1/b2b.' in path else 'company' if '/api1/' in path else 'monitor' if '/monitor-' in path else 'issuer')
   ops.append({'id':oid,'method':method.upper(),'route':route,'module':path,'base':op.get('servers',doc.get('servers'))[0]['url'],'scope':auth,'schema':ps,'parameters':params,'body':body,'binary':binary,'security':op.get('security',[]),'effects':op.get('x-operation-effects',{}),'status':{},'enabled':op.get('x-sdk-generation-enabled',True) is not False,'redirectStatuses':[int(code) for code,response in op['responses'].items() if code.isdigit() and 300<=int(code)<400 and any(h.lower()=='location' for h in response.get('headers',{}))],'responseMedia':sorted({media for response in resp.values() for media in response.get('content',{})}),'responseSelections':{code:{media:content.get('schema') for media,content in response.get('content',{}).items()} for code,response in op['responses'].items()},'responseSchema':jsonres[0] if jsonres else None,'responseType':rt,'parametersType':pn})
methods.append('}')
(ROOT/'src/Webmania.Sdk/Models.g.cs').write_bytes(('\n'.join(models)+'\n').encode('utf-8'))
(ROOT/'src/Webmania.Sdk/Operations.g.cs').write_bytes(('\n'.join(methods)+'\n').encode('utf-8'))
(ROOT/'src/Webmania.Sdk/operations.json').write_bytes((json.dumps(ops,ensure_ascii=False,separators=(',',':'))+'\n').encode('utf-8'))
(ROOT/'contracts.lock.json').write_bytes((json.dumps({'repository':'https://github.com/webmaniabr/webmania-openapi','contract_digest':digest,'modules':locks,'operations':len(ops),'enabled':sum(x['enabled'] for x in ops),'status':'partial_fiscal_program'},indent=2)+'\n').encode('utf-8'))
print(json.dumps({'models':len(declarations),'operations':len(ops),'modules':len(locks),'enabled':sum(x['enabled'] for x in ops)}))
